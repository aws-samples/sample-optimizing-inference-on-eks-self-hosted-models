"""``scripts/lib/common.sh``: the keys of the platform config never reach the shell as code.

Contract (static-analysis observation on the ``eval`` of the config parser):

* every non-blank line of ``PLATFORM_ENV`` that is not a ``#`` comment is ``KEY=VALUE`` with ``KEY`` matching
  ``^[A-Z][A-Z0-9_]*$`` (the ``KEY_RE`` of ``scripts/gen_env.py``, which writes the file); it becomes ``CFG_<KEY>``
  with the value kept byte for byte (no expansion, no word splitting), an empty value included;
* any other key is refused before anything runs: sourcing the library exits non-zero and the error names the
  file, the offending key and the pattern. A crafted key (``;``, ``$(...)``, a backtick) runs nothing;
* the parser assigns without ``eval`` (``printf -v`` after the check), and the placeholder config of the suite
  (``manifests/config/platform.env.example``) still parses into the same ``CFG_*`` values.
"""

from __future__ import annotations

import re
from pathlib import Path

import lib_scripts as S
import pytest
import trackq_scripts as T

COMMON = S.SCRIPTS_DIR / "lib" / "common.sh"
KEY_PATTERN = "^[A-Z][A-Z0-9_]*$"


def _source(tmp: Path, lines: list[str], snippet: str = "true") -> S.Result:
    """Source common.sh with ``PLATFORM_ENV`` = a file holding ``lines``, then run ``snippet``."""
    tmp.mkdir(parents=True, exist_ok=True)
    cfg = tmp / "platform.env"
    cfg.write_text("".join(f"{ln}\n" for ln in lines))
    return T.run_common(S.Sandbox(tmp / "sb", {}), snippet, {"PLATFORM_ENV": str(cfg)})


def _payloads(sentinel: Path) -> dict[str, str]:
    """Keys that would run a command under ``eval "CFG_${key}=..."`` (each creates ``sentinel``)."""
    return {
        "semicolon": f'A;: >"{sentinel}";B',
        "command substitution": f'A$(: >"{sentinel}")',
        "backticks": f'A`: >"{sentinel}"`',
    }


@pytest.mark.parametrize("kind", ["semicolon", "command substitution", "backticks"])
def test_a_crafted_key_runs_nothing_and_is_refused(tmp_path: Path, kind: str) -> None:
    sentinel = tmp_path / "pwned"
    key = _payloads(sentinel)[kind]
    res = _source(tmp_path, ["AWS_REGION=us-east-2", f"{key}=1"], 'printf "%s" "${CFG_AWS_REGION:-}"')
    assert not sentinel.exists(), f"the key {key!r} ran a command while common.sh parsed the config"
    assert res.rc != 0, f"common.sh accepted the key {key!r}: {res.stdout}{res.stderr}"
    assert key in res.stderr and KEY_PATTERN in res.stderr, res.stderr
    assert "platform.env" in res.stderr, res.stderr


@pytest.mark.parametrize("key", ["bad-key", "lower", "1ABC", "_ABC", "A B", "A.B", " AWS_REGION", "AWS_REGION "])
def test_a_key_outside_the_pattern_is_refused(tmp_path: Path, key: str) -> None:
    res = _source(tmp_path, [f"{key}=x"])
    assert res.rc != 0, f"common.sh accepted the key {key!r}"
    assert KEY_PATTERN in res.stderr, res.stderr


def test_a_valid_key_keeps_its_value_verbatim(tmp_path: Path) -> None:
    value = "a;b $(echo no) `echo no` \"q\" 'q' * ? \\ ${HOME} = x"
    res = _source(tmp_path, [f"V1={value}"], 'printf "%s" "$CFG_V1"')
    assert res.rc == 0, res.stderr
    assert res.stdout == value


def test_comments_blank_lines_and_empty_values_still_parse(tmp_path: Path) -> None:
    lines = ["# GENERATED by scripts/gen_env.py", "", "A_1=", "B2=x", "#C=commented out"]
    res = _source(tmp_path, lines, 'printf "%s|%s|%s" "${CFG_A_1-unset}" "$CFG_B2" "${CFG_C-unset}"')
    assert res.rc == 0, res.stderr
    assert res.stdout == "|x|unset"


def test_the_placeholder_config_still_parses_into_the_same_values(tmp_path: Path) -> None:
    for key, want in sorted(T.CFG.items()):
        assert T.common_value(tmp_path / key, f'"$CFG_{key}"') == want, key


def test_common_sh_assigns_the_config_without_eval() -> None:
    code = [ln for ln in COMMON.read_text().splitlines() if not ln.lstrip().startswith("#")]
    assert not [ln for ln in code if re.search(r"\beval\b", ln)], "lib/common.sh must not eval the platform config"
    assert any("printf -v" in ln for ln in code), "lib/common.sh assigns CFG_<KEY> with printf -v after the key check"
