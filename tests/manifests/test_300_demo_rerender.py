"""Contract of manifests/demo/rerender/rerender.py: re-render a demo take from Prometheus history (qa, RED).

Why: the live capture of a take can record 'No data' (it opened the demo-take dashboard ~240 s before the replay with an absolute
range in the future, so the time-range-dependent `namespace` variable only offered the other scenario and Grafana replaced
var-namespace). The series are intact in Prometheus, so a CPU-only Job re-renders the take view from the recorded history, one frame per
step, and a compose Job turns the two re-rendered webms into the side-by-side clips. The tool was proven on the W3-16K r32 and r25 runs;
this file ports its 88 tests to the repo layout and adds the repo contract.

Port adaptations (nothing else changed, no expectation was relaxed):
* the module lives in `manifests/demo/rerender/rerender.py` (next to `manifests/demo/capture`);
* bucket, region and the bench ECR repo are NOT literals of the module: they come from the environment (RESULTS_BUCKET, AWS_REGION,
  BENCH_REPO; the CLI can read them from `manifests/config/platform.env`), so the tests use fake values; the ffmpeg image is
  `$BENCH_REPO:ffmpeg-9.0.2-cli-ls86@sha256:...` (the proven digest);
* the archived matrix driver is no longer loaded: `compose_job`, the labels, the take cells and the pinned images are in the module, the
  compose script is vendored as `compose.sh` and shipped by the ConfigMap `R.SCRIPTS_CM` generated by the kustomization of the directory.

Contract (unchanged from the proven tool) in the docstring of the tests below; pure helpers, no cluster/S3/network access in tests.
"""
