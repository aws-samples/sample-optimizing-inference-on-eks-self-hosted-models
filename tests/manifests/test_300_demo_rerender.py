def _containers(job):
    s = job["spec"]["template"]["spec"]
    return (s.get("initContainers") or []) + s["containers"]


def _assert_cpu_only_pinned(job):
    s = job["spec"]["template"]["spec"]
    assert s["nodeSelector"] == {"karpenter.sh/nodepool": "cpu-demo"}
    text = json.dumps(job)
    assert "nvidia.com/gpu" not in text and "gpu" not in json.dumps(s.get("tolerations", [])).lower()
    for c in _containers(job):
        assert DIGEST.search(c["image"]), f"{c['name']}: image not pinned by digest: {c['image']}"
    assert job["metadata"]["namespace"] == "bench" and s["restartPolicy"] == "Never" and job["spec"]["backoffLimit"] == 0
    assert s["serviceAccountName"] == "matrix-driver"


