REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
MANIFESTS_DIR="${MANIFESTS_DIR:-$REPO_ROOT/manifests}"
SCRIPT_NAME="$(basename "$0")"
# ASCII collation: a locale where [a-z] also matches uppercase would weaken the input
# validation (e.g. a bad --block Block1 slipping through).
export LC_ALL=C

# log <message...>: one structured line on stderr.
log() {
  printf '%s %s %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$SCRIPT_NAME" "$*" >&2
}

# die <message...>: log and exit 1.
die() {
  log "error: $*"
  exit 1
}

# Single platform config source, shared with the manifests (manifests/config/platform.env, generated by
# scripts/gen_env.py). Parsed into CFG_<KEY> variables; callers read them as defaults (an explicit env var
# wins). The caller's ambient AWS_REGION is deliberately NOT used for S3: the region comes from here.
# An explicit PLATFORM_ENV wins. Blank lines and '#' comments are skipped; every other key must match
# ^[A-Z][A-Z0-9_]*$ (the KEY_RE of gen_env.py) or the script stops before anything runs. The key is checked
# before it becomes a variable name and printf -v assigns the value verbatim: nothing of the file is run.
PLATFORM_ENV="${PLATFORM_ENV:-$MANIFESTS_DIR/config/platform.env}"
if [ -f "$PLATFORM_ENV" ]; then
  while IFS='=' read -r _k _v; do
    case "$_k" in
      '' | \#*) continue ;;
      [!A-Z]* | *[!A-Z0-9_]*)
        die "malformed key '$_k' in $PLATFORM_ENV: a key must match ^[A-Z][A-Z0-9_]*\$ (KEY=VALUE lines, '#' comments)"
        ;;
    esac
    printf -v "CFG_${_k}" '%s' "$_v"
  done <"$PLATFORM_ENV"
fi

