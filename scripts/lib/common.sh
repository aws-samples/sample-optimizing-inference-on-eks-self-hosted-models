# is_uint <value>: true for a non-empty string of digits.
is_uint() {
  case "${1:-}" in
    '' | *[!0-9]*) return 1 ;;
    *) return 0 ;;
  esac
}

# router_env_value <rr|kv>: DYN_ROUTER_MODE value rendered by frontends/<mode>.
router_env_value() {
  case "${1:-}" in
    rr) echo round-robin ;;
    kv) echo kv ;;
    *) return 1 ;;
  esac
}

