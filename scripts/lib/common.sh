# kube <kubectl args...>: kubectl pinned to $KUBE_CONTEXT when set. One argv token on purpose
# (--context=<value>, never "--context VALUE"), placed before any "--" of exec. Every cluster
# call goes through it; offline `kubectl kustomize` / `--local` calls may stay bare.
kube() {
  if [ -n "${KUBE_CONTEXT:-}" ]; then
    kubectl --context="$KUBE_CONTEXT" "$@"
  else
    kubectl "$@"
  fi
}

# require_kube_target: refuse to touch a cluster chosen implicitly. In-cluster (KUBERNETES_SERVICE_HOST
# set) the ServiceAccount is the target. Off-cluster KUBE_CONTEXT is mandatory, so the current context of
# a workstation (possibly another cluster) is never used; when the platform config names its cluster
# (CLUSTER_NAME), KUBE_CONTEXT must be that cluster, as a context of that name or as its EKS ARN
# (arn:aws:eks:<region>:<account>:cluster/<name>). Only the config's CLUSTER_NAME counts, never the
# caller's environment.
require_kube_target() {
  [ -z "${KUBERNETES_SERVICE_HOST:-}" ] || return 0
  [ -n "${KUBE_CONTEXT:-}" ] ||
    die "KUBE_CONTEXT is not set: refusing to use the current kubectl context off-cluster (export KUBE_CONTEXT=<context of the demo cluster>)"
  [ -n "${CFG_CLUSTER_NAME:-}" ] || return 0
  case "$KUBE_CONTEXT" in
    "$CFG_CLUSTER_NAME" | arn:aws:eks:*:*:cluster/"$CFG_CLUSTER_NAME") ;;
    *) die "the platform config ($PLATFORM_ENV) names the cluster $CFG_CLUSTER_NAME: KUBE_CONTEXT='$KUBE_CONTEXT' is another cluster (export KUBE_CONTEXT=$CFG_CLUSTER_NAME or its EKS ARN)" ;;
  esac
}

# node_shell <command...>: run a command in the GPU-node helper pod (node-ops).
node_shell() {
  kube exec -n "$NODE_OPS_NS" "$NODE_SHELL" -c shell -- "$@" </dev/null
}

# replace_finished_job <name>: clear the way for a new run of Job <name> in node-ops (a Job's pod
# template is immutable, so a re-submit needs the old object gone). The state is read first: an
# absent Job needs nothing, a finished one (Complete=True or Failed=True) is deleted, and a Job
# that is still active (no terminal condition yet) is never deleted: refuse instead (P-5/P-22).
replace_finished_job() {
  local job="$1" json state
  json="$(kube get job "$job" -n "$NODE_OPS_NS" -o json --ignore-not-found </dev/null)" ||
    die "cannot read the state of Job $NODE_OPS_NS/$job; refusing to replace it"
  state=absent
  if [ -n "$json" ]; then
    state="$(jq -r '
      if .kind == "List" then (if ((.items // []) | length) == 0 then "absent" else "unknown" end)
      elif any((.status.conditions // [])[]; (.type == "Complete" or .type == "Failed") and .status == "True") then "finished"
      else "active" end' <<<"$json")" || die "cannot parse the state of Job $NODE_OPS_NS/$job"
  fi
  case "$state" in
    absent | finished) ;;
    active)
      die "Job $NODE_OPS_NS/$job is still active (no Complete or Failed condition): refusing to delete it or submit over it; wait until it is Complete or Failed, then re-run"
      ;;
    *) die "unexpected answer reading Job $NODE_OPS_NS/$job (state '$state'); refusing to replace it" ;;
  esac
  log "step=replace-job job=$NODE_OPS_NS/$job state=$state"
  kube delete job "$job" -n "$NODE_OPS_NS" --ignore-not-found --wait=true --timeout=120s </dev/null
}
