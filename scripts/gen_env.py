"""Write the platform and sample env files from the ``terraform/cluster`` outputs.

Reads ``terraform output -json`` of ``terraform/cluster`` (``--from-json FILE`` or, without it,
``terraform -chdir=<repo>/terraform/cluster output -json``) and writes:

* ``manifests/config/platform.env``: the file the kustomize ``config`` component and
  ``scripts/lib/common.sh`` read; ``platform_env`` plus ``MODEL_ID``, ``MODEL_REVISION`` and
  ``RUNTIME_IMAGE`` of ``sample_env``;
* ``config/sample.env``: ``sample_env`` (model and workload settings), sourceable by a shell.

Both also carry the model path: ``MODEL_S3_PREFIX`` (the ``sample_env`` value when Terraform sets it,
else ``<MODEL_ID>/<MODEL_REVISION>``) and ``MODEL_S3_URI`` = ``s3://<MODEL_BUCKET>/<MODEL_S3_PREFIX>``,
where scripts/10-stage-model.sh stages the model and 11-prefetch.sh reads it. ``HF_TOKEN`` is never
generated: a token in any output is refused. The optional token of a gated model is exported in the shell
that runs scripts/10-stage-model.sh (it reads the process environment) and never written to these files,
which every run overwrites.

Both are plain ``KEY=VALUE`` lines under a ``# GENERATED`` header, sorted, so two runs on the same
outputs are byte-identical. Every check runs before anything is written: a refusal exits 1, writes
nothing and never prints an output value (only key names).

Track Q gate: the Track Q manifests select ``karpenter.sh/nodepool: gpu-b200-cb`` with 8 GPUs per
node and serve ``Qwen/Qwen3.8-27B-FP8``. Any other shape (pool name, GPUs per node, several pools)
or model is refused unless ``--allow-untested`` is given; then the script warns "manifests
untested" and, for another shape, sets ``GPU_SHAPE_SUPPORTED=terraform-only``. With several pools
the single-value GPU keys are dropped (they would depend on the order of ``gpu_instance_types``);
``GPU_POOLS`` lists every pool. An empty ``RUNTIME_IMAGE`` is always refused (the renders would
carry an invalid image).

Example:
    python3 scripts/gen_env.py                  # after `terraform apply` in terraform/cluster
    python3 scripts/gen_env.py --from-json out.json --allow-untested
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

LOG = logging.getLogger("gen_env")

SCRIPT_REPO = Path(__file__).resolve().parents[1]
PLATFORM_ENV_REL = Path("manifests") / "config" / "platform.env"
TRACKQ_POOL = "gpu-b200-cb"
TRACKQ_GPUS_PER_NODE = "8"
TRACKQ_MODEL = "Qwen/Qwen3.8-27B-FP8"

REQUIRED_OUTPUTS = ("platform_env", "sample_env", "gpu_pools")
REQUIRED_SAMPLE_KEYS = ("MODEL_ID", "MODEL_REVISION", "RUNTIME_IMAGE")
SINGLE_VALUE_KEYS = (
    "GPU_NODEPOOL",
    "GPU_PRODUCT",
    "GPUS_PER_NODE",
    "EFA_INTERFACES_PER_NODE",
    "GPU_MEMORY_GIB_PER_GPU",
    "HOST_MEMORY_GIB",
    "EPHEMERAL_MIN_GIB",
    "GPU_INSTANCE_TYPES",
    "GPU_AZ",
)

KEY_RE = re.compile(r"[A-Z][A-Z0-9_]*")
# Keys no Terraform output may carry (a token would sit in the state and in the generated files).
FORBIDDEN_KEYS = ("HF_TOKEN",)
# One S3 key segment of MODEL_S3_PREFIX; "." and ".." are refused on top of it.
PREFIX_SEGMENT_RE = re.compile(r"[A-Za-z0-9._-]+")
# The format the kustomize configMapGenerator and scripts/lib/common.sh accept: no quotes, spaces,
# $, # or backticks.
VALUE_RE = re.compile(r"[^\s\"'#$`]*")
HEADER = (
    "# GENERATED by scripts/gen_env.py from the terraform/cluster outputs:"
    " do not edit, re-run the script."
)


class RefusalError(Exception):
    """An input the script refuses to turn into env files (messages never hold output values)."""


def parse_args(argv: list[str]) -> argparse.Namespace:
    """Parse the command line.

    Args:
        argv: Arguments without the program name.

    Returns:
        The parsed arguments.
    """
    parser = argparse.ArgumentParser(description="Write platform.env and sample.env.")
    parser.add_argument(
        "--from-json", type=Path, help="terraform output -json file (default: run terraform)"
    )
    parser.add_argument(
        "--repo-root", type=Path, default=SCRIPT_REPO, help="repository root (default: this repo)"
    )
    parser.add_argument(
        "--platform-out", type=Path, help=f"platform.env path (default: <repo>/{PLATFORM_ENV_REL})"
    )
    parser.add_argument(
        "--sample-out", type=Path, help="sample.env path (default: <repo>/config/sample.env)"
    )
    parser.add_argument(
        "--allow-untested",
        action="store_true",
        help="write a GPU shape or model the Track Q manifests were not tested with",
    )
    return parser.parse_args(argv)


def load_outputs(from_json: Path | None, repo_root: Path) -> dict[str, Any]:
    """Return the ``terraform output -json`` document.

    Args:
        from_json: File holding the JSON, or None to run ``terraform output -json``.
        repo_root: Repository root (``terraform/cluster`` lives under it).

    Returns:
        The decoded outputs, keyed by output name.

    Raises:
        RefusalError: The file or the command is missing or fails, or the JSON is not an object.
    """
    if from_json is not None:
        try:
            text = from_json.read_text()
        except OSError as exc:
            raise RefusalError(f"cannot read {from_json}: {exc.strerror}") from None
    else:
        chdir = repo_root / "terraform" / "cluster"
        # terraform comes from PATH like in every other script, resolved here so the argv runs it by path.
        terraform = shutil.which("terraform")
        if terraform is None:
            raise RefusalError("terraform is not on PATH (or pass --from-json)")
        # A list argv, no shell: constants plus one "-chdir=<path>" token, so the --repo-root path (the
        # operator's own CLI value) stays inside that single argument, never an option of its own.
        argv = [terraform, f"-chdir={chdir}", "output", "-json"]
        # nosemgrep: python.lang.security.audit.dangerous-subprocess-use-audit, dangerous-subprocess-use-audit -- list argv, resolved terraform, one inert -chdir= token
        proc = subprocess.run(argv, capture_output=True, text=True, check=False)  # nosec B603 -- list argv, no shell
        if proc.returncode != 0:
            raise RefusalError(f"terraform output -json failed in {chdir} (exit {proc.returncode})")
        text = proc.stdout
    try:
        doc = json.loads(text)
    except json.JSONDecodeError:
        raise RefusalError("the terraform outputs are not valid JSON") from None
    if not isinstance(doc, dict):
        raise RefusalError("the terraform outputs are not a JSON object")
    return doc


def required_values(outputs: dict[str, Any]) -> dict[str, Any]:
    """Return the values of the required outputs, refusing missing and sensitive ones.

    Args:
        outputs: The ``terraform output -json`` document.

    Returns:
        Output name -> value, for every name of ``REQUIRED_OUTPUTS``.

    Raises:
        RefusalError: The document has no output at all (no apply yet), some required outputs are missing or
            malformed (the last apply did not finish; the message names them), or one is sensitive.
    """
    if not outputs:
        raise RefusalError(
            f"terraform/cluster has no outputs (required: {', '.join(REQUIRED_OUTPUTS)}): it was never applied, "
            "or this is not the state of your stack (run terraform apply in terraform/cluster first)"
        )
    missing = [
        name
        for name in REQUIRED_OUTPUTS
        if not isinstance(outputs.get(name), dict) or "value" not in outputs[name]
    ]
    if missing:
        raise RefusalError(
            f"terraform output {', '.join(missing)} missing, while the state of terraform/cluster holds "
            f"{len(outputs)} other output(s): the last terraform apply failed or stopped before it created "
            f"{'it' if len(missing) == 1 else 'them'}; read the errors of that apply, fix them and apply again "
            "(to tear the partial stack down instead: docs/DEPLOY.md#teardown)"
        )
    for name in REQUIRED_OUTPUTS:
        if outputs[name].get("sensitive"):
            raise RefusalError(f"terraform output {name} is sensitive: refusing to write it to a file")
    return {name: outputs[name]["value"] for name in REQUIRED_OUTPUTS}


def env_map(name: str, value: Any) -> dict[str, str]:
    """Validate an env output: uppercase keys, plain string values.

    Args:
        name: Output name (for messages).
        value: The output value.

    Returns:
        The validated mapping.

    Raises:
        RefusalError: A key or value is unsafe, or a forbidden key such as HF_TOKEN is present (the
            message names the key, never the value).
    """
    if not isinstance(value, dict):
        raise RefusalError(f"terraform output {name} is not a map")
    for key in FORBIDDEN_KEYS:
        if key in value:
            raise RefusalError(
                f"{name}: {key} must never be a Terraform output (it would sit in the state and in "
                "the generated files); keep it in the untracked env only"
            )
    for key, val in value.items():
        if not KEY_RE.fullmatch(str(key)):
            raise RefusalError(f"{name}: key {key!r} is not an uppercase env name")
        if not isinstance(val, str) or not VALUE_RE.fullmatch(val):
            raise RefusalError(f"{name}: the value of {key} holds quotes, spaces, $, # or `")
    return dict(value)


def pool_map(value: Any) -> dict[str, Any]:
    """Validate the ``gpu_pools`` output.

    Args:
        value: The output value.

    Returns:
        Pool name -> facts.

    Raises:
        RefusalError: The value is not a non-empty map.
    """
    if not isinstance(value, dict) or not value:
        raise RefusalError("terraform output gpu_pools is empty or not a map")
    return value


def model_path(platform: dict[str, str], sample: dict[str, str]) -> tuple[str, str]:
    """Return MODEL_S3_PREFIX and MODEL_S3_URI, the model path of the generated env.

    Args:
        platform: platform_env (MODEL_BUCKET).
        sample: sample_env (MODEL_ID, MODEL_REVISION and, when Terraform sets it, MODEL_S3_PREFIX).

    Returns:
        (prefix, ``s3://<MODEL_BUCKET>/<prefix>``), both without a trailing slash.

    Raises:
        RefusalError: MODEL_BUCKET is missing, or the prefix is not a safe S3 key prefix (the
            message never holds the value).
    """
    prefix = sample.get("MODEL_S3_PREFIX", f"{sample['MODEL_ID']}/{sample['MODEL_REVISION']}")
    segments = prefix.split("/")
    if not all(PREFIX_SEGMENT_RE.fullmatch(seg) and seg not in (".", "..") for seg in segments):
        raise RefusalError(
            "sample_env: MODEL_S3_PREFIX is not a safe S3 key prefix (segments of A-Za-z0-9._- "
            "joined by single slashes, no dot or dot-dot segment, no slash at either end)"
        )
    bucket = platform.get("MODEL_BUCKET")
    if not bucket:
        raise RefusalError("platform_env lacks MODEL_BUCKET (needed for MODEL_S3_URI)")
    return prefix, f"s3://{bucket}/{prefix}"


def untested_reasons(
    platform: dict[str, str], sample: dict[str, str], pools: dict[str, Any]
) -> tuple[list[str], bool]:
    """Compare the outputs with the shape and model the Track Q manifests were tested with.

    Args:
        platform: platform_env.
        sample: sample_env.
        pools: gpu_pools (pool name -> facts).

    Returns:
        The reasons the outputs are untested, and whether the GPU shape is one of them.
    """
    reasons: list[str] = []
    shape_ok = (
        list(pools) == [TRACKQ_POOL]
        and platform.get("GPU_NODEPOOL") == TRACKQ_POOL
        and platform.get("GPUS_PER_NODE") == TRACKQ_GPUS_PER_NODE
    )
    if not shape_ok:
        reasons.append(
            f"the Track Q manifests select exactly one pool {TRACKQ_POOL} with "
            f"{TRACKQ_GPUS_PER_NODE} GPUs per node (the outputs have {len(pools)} pool(s) "
            "or another GPU_NODEPOOL / GPUS_PER_NODE)"
        )
    if sample.get("MODEL_ID") != TRACKQ_MODEL:
        reasons.append(
            "the Track Q manifests and scripts/lib/common.sh serve and prefetch "
            f"{TRACKQ_MODEL} only"
        )
    return reasons, not shape_ok


def build(
    platform: dict[str, str],
    sample: dict[str, str],
    pools: dict[str, Any],
    *,
    allow_untested: bool,
) -> tuple[dict[str, str], dict[str, str]]:
    """Apply the Track Q rules and return the contents of platform.env and sample.env.

    Args:
        platform: Validated platform_env.
        sample: Validated sample_env.
        pools: gpu_pools.
        allow_untested: Write an untested shape or model (with a warning).

    Returns:
        (platform.env mapping, sample.env mapping), both with MODEL_S3_PREFIX and MODEL_S3_URI.

    Raises:
        RefusalError: An empty runtime image, a missing sample key, an unsafe model path, or an
            untested shape or model without ``allow_untested``.
    """
    missing = [k for k in REQUIRED_SAMPLE_KEYS if k not in sample]
    if missing:
        raise RefusalError(f"sample_env lacks {missing}")
    if not sample["RUNTIME_IMAGE"]:
        raise RefusalError(
            "RUNTIME_IMAGE is empty: set runtime_image in terraform/cluster to the image of "
            "versions.env (or its ECR mirror), pinned by digest, and run terraform apply"
        )
    prefix, uri = model_path(platform, sample)
    reasons, shape_untested = untested_reasons(platform, sample, pools)
    if reasons and not allow_untested:
        raise RefusalError("; ".join(reasons) + " (pass --allow-untested to write it anyway)")
    out = dict(platform)
    if len(pools) > 1:
        for key in SINGLE_VALUE_KEYS:
            out.pop(key, None)
    for key in REQUIRED_SAMPLE_KEYS:
        out[key] = sample[key]
    if reasons:
        LOG.warning("event=untested message=%r", "manifests untested: " + "; ".join(reasons))
        if shape_untested:
            out["GPU_SHAPE_SUPPORTED"] = "terraform-only"
    sample_out = dict(sample)
    for env in (out, sample_out):
        env["MODEL_S3_PREFIX"] = prefix
        env["MODEL_S3_URI"] = uri
    return out, sample_out


def render(values: dict[str, str]) -> str:
    """Return the file text: the GENERATED header and sorted KEY=VALUE lines.

    Args:
        values: Env mapping.

    Returns:
        The file content.
    """
    return "\n".join([HEADER, *(f"{k}={values[k]}" for k in sorted(values))]) + "\n"


def write_atomic(path: Path, text: str) -> None:
    """Write ``text`` to ``path`` through a temporary file in the same directory.

    Args:
        path: Destination.
        text: Content.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(text)
        tmp.replace(path)
    except BaseException:
        tmp.unlink(missing_ok=True)
        raise


def prepare(args: argparse.Namespace) -> list[tuple[Path, str]]:
    """Run every check and return what to write, without writing anything.

    Args:
        args: Parsed command line.

    Returns:
        (path, text) of platform.env and sample.env.

    Raises:
        RefusalError: Any refusal of the contract (see the module docstring).
    """
    outputs = load_outputs(args.from_json, args.repo_root)
    values = required_values(outputs)
    platform = env_map("platform_env", values["platform_env"])
    sample = env_map("sample_env", values["sample_env"])
    pools = pool_map(values["gpu_pools"])
    platform_out, sample_out = build(platform, sample, pools, allow_untested=args.allow_untested)
    platform_path = args.platform_out or args.repo_root / PLATFORM_ENV_REL
    sample_path = args.sample_out or args.repo_root / "config" / "sample.env"
    return [(platform_path, render(platform_out)), (sample_path, render(sample_out))]


def main(argv: list[str]) -> int:
    """Run the generator.

    Args:
        argv: Arguments without the program name.

    Returns:
        Exit code: 0 written, 1 refused.
    """
    logging.basicConfig(
        level=logging.INFO, stream=sys.stderr, format="gen_env level=%(levelname)s %(message)s"
    )
    args = parse_args(argv)
    try:
        files = prepare(args)
    except RefusalError as exc:
        # An expected refusal of the input, not a crash: no traceback.
        LOG.error("event=refused reason=%r", str(exc))
        return 1
    for path, text in files:
        write_atomic(path, text)
    LOG.info("event=written files=%s", ",".join(str(path) for path, _ in files))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
